    """Return monthly BTM nameplate history and derived ratios."""
    mode = str(config["btm"]["mode"]).lower().strip()
    current_mw = float(config["btm"]["current_nameplate_mw"])
    impact_mw = float(config["btm"]["max_observed_impact_mw"])

    if mode == "hardcoded":
        df = pd.read_csv(
            io.StringIO(HARDCODED_BTM_SOLAR_MONTHLY_TSV), sep=r"\s+", engine="python"
        )
    elif mode == "csv":
        df = pd.read_csv(config["btm"]["tsv_path"])
    elif mode == "sql":
        # Placeholder (future): read from SQL table
        raise NotImplementedError("SQL BTM loader not implemented yet.")
    else:
        raise ValueError(f"Unsupported BTM mode: {mode}")

    df["DT"] = pd.to_datetime(dict(year=df["YEAR"], month=df["MONTH"], day=1))
    df["Nameplate_MW"] = pd.to_numeric(df["TTL_SLR_KW_RT"], errors="coerce") / 1000.0
    df.sort_values("DT", inplace=True)

    # Extend future months as flat nameplate to keep ratios defined
    extend_n = int(config["btm"]["extend_future_months"])
    if extend_n > 0:
        last = df["DT"].max()
        ext_rows = []
        last_np = df.loc[df["DT"] == last, "TTL_SLR_KW_RT"].iloc[0]
        for i in range(1, extend_n + 1):
            ext_dt = last + relativedelta(months=i)
            ext_rows.append(
                {
                    "MONTH": ext_dt.month,
                    "YEAR": ext_dt.year,
                    "DT": ext_dt,
                    "TTL_SLR_KW_RT": last_np,
                    "Nameplate_MW": last_np / 1000.0,
                }
            )
        df_ext = pd.DataFrame(ext_rows)
        df = pd.concat([df, df_ext], ignore_index=True)

    df["Capacity_Ratio_To_Current"] = df["Nameplate_MW"] / max(current_mw, 1e-6)
    # Simple proxy scaling using observed ratio
    df["Impact_Cap_MW"] = df["Capacity_Ratio_To_Current"] * impact_mw
    return df[["DT", "Nameplate_MW", "Capacity_Ratio_To_Current", "Impact_Cap_MW"]]
